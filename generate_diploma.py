# -------------------------- Стилевые помощники --------------------------

def _set_run_font(run, size=14, bold=False, italic=False):
    run.font.name = "Times New Roman"
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("ascii", "hAnsi", "eastAsia", "cs"):
        rfonts.set(qn(f"w:{attr}"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def _set_paragraph_format(p, *, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                          first_line_indent=Cm(1.25),
                          line_spacing=1.5,
                          space_before=Pt(0),
                          space_after=Pt(0),
                          left_indent=None,
                          keep_with_next=False):
    pf = p.paragraph_format
    pf.alignment = alignment
    pf.first_line_indent = first_line_indent
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = line_spacing
    pf.space_before = space_before
    pf.space_after = space_after
    if left_indent is not None:
        pf.left_indent = left_indent
    pf.keep_with_next = keep_with_next


def add_paragraph(doc, text, *, bold=False, italic=False,
                  alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                  first_line_indent=Cm(1.25),
                  size=14,
                  space_before=Pt(0),
                  space_after=Pt(0)):
    p = doc.add_paragraph()
    _set_paragraph_format(p, alignment=alignment,
                          first_line_indent=first_line_indent,
                          space_before=space_before,
                          space_after=space_after)
    run = p.add_run(text)
    _set_run_font(run, size=size, bold=bold, italic=italic)
    return p


def add_centered(doc, text, *, bold=False, size=14, space_before=Pt(0), space_after=Pt(0)):
    return add_paragraph(doc, text, bold=bold, size=size,
                         alignment=WD_ALIGN_PARAGRAPH.CENTER,
                         first_line_indent=Cm(0),
                         space_before=space_before,
                         space_after=space_after)


def add_chapter_heading(doc, text):
    doc.add_page_break()
    p = doc.add_paragraph()
    _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.CENTER,
                          first_line_indent=Cm(0),
                          space_before=Pt(0),
                          space_after=Pt(18),
                          keep_with_next=True)
    run = p.add_run(text.upper())
    _set_run_font(run, size=14, bold=True)


def add_section_heading(doc, text, *, level=2):
    p = doc.add_paragraph()
    _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.LEFT,
                          first_line_indent=Cm(1.25),
                          space_before=Pt(12),
                          space_after=Pt(6),
                          keep_with_next=True)
    run = p.add_run(text)
    _set_run_font(run, size=14, bold=True)


def add_bullet_list(doc, items):
    for item in items:
        p = doc.add_paragraph()
        _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                              first_line_indent=Cm(0),
                              left_indent=Cm(1.25),
                              space_before=Pt(0),
                              space_after=Pt(0))
        run = p.add_run("– " + item)
        _set_run_font(run, size=14)


def add_numbered_list(doc, items):
    for i, item in enumerate(items, start=1):
        p = doc.add_paragraph()
        _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                              first_line_indent=Cm(0),
                              left_indent=Cm(1.25),
                              space_before=Pt(0),
                              space_after=Pt(0))
        run = p.add_run(f"{i}. " + item)
        _set_run_font(run, size=14)


def add_code_block(doc, code, *, language="Kotlin"):
    caption = doc.add_paragraph()
    _set_paragraph_format(caption, alignment=WD_ALIGN_PARAGRAPH.LEFT,
                          first_line_indent=Cm(0),
                          space_before=Pt(6),
                          space_after=Pt(3))
    run = caption.add_run(f"Листинг ({language}):")
    _set_run_font(run, size=12, italic=True)

    p = doc.add_paragraph()
    _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.LEFT,
                          first_line_indent=Cm(0),
                          line_spacing=1.0,
                          space_before=Pt(0),
                          space_after=Pt(6))
    run = p.add_run(code)
    run.font.name = "Consolas"
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("ascii", "hAnsi", "eastAsia", "cs"):
        rfonts.set(qn(f"w:{attr}"), "Consolas")
    run.font.size = Pt(11)


def add_table(doc, headers, rows, *, caption=None):
    if caption:
        p = doc.add_paragraph()
        _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.CENTER,
                              first_line_indent=Cm(0),
                              space_before=Pt(6),
                              space_after=Pt(3))
        run = p.add_run(caption)
        _set_run_font(run, size=14)

    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = ""
        cell_p = hdr_cells[i].paragraphs[0]
        _set_paragraph_format(cell_p, alignment=WD_ALIGN_PARAGRAPH.CENTER,
                              first_line_indent=Cm(0))
        run = cell_p.add_run(h)
        _set_run_font(run, size=12, bold=True)

    for row in rows:
        row_cells = table.add_row().cells
        for i, value in enumerate(row):
            row_cells[i].text = ""
            cell_p = row_cells[i].paragraphs[0]
            _set_paragraph_format(cell_p, alignment=WD_ALIGN_PARAGRAPH.LEFT,
                                  first_line_indent=Cm(0))
            run = cell_p.add_run(str(value))
            _set_run_font(run, size=12)


def add_placeholder(doc, text):
    p = doc.add_paragraph()
    _set_paragraph_format(p, alignment=WD_ALIGN_PARAGRAPH.CENTER,
                          first_line_indent=Cm(0),
                          space_before=Pt(6),
                          space_after=Pt(6))
    run = p.add_run(text)
    _set_run_font(run, size=12, italic=True)


def add_page_numbers(doc):
    for section in doc.sections:
        footer = section.footer
        p = footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        _set_run_font(run, size=12)

        fld_begin = OxmlElement("w:fldChar")
        fld_begin.set(qn("w:fldCharType"), "begin")
        instr = OxmlElement("w:instrText")
        instr.set(qn("xml:space"), "preserve")
        instr.text = "PAGE"
        fld_sep = OxmlElement("w:fldChar")
        fld_sep.set(qn("w:fldCharType"), "separate")
        fld_end = OxmlElement("w:fldChar")
        fld_end.set(qn("w:fldCharType"), "end")
        r = run._r
        r.append(fld_begin)
        r.append(instr)
        r.append(fld_sep)
        r.append(fld_end)


def setup_document(doc):
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("ascii", "hAnsi", "eastAsia", "cs"):
        rfonts.set(qn(f"w:{attr}"), "Times New Roman")

    for section in doc.sections:
        section.page_height = Cm(29.7)
        section.page_width = Cm(21.0)
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(3)
        section.right_margin = Cm(1.5)


