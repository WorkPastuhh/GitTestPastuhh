def _set_run_font(run, size=14, bold=False, italic=False):
    """Устанавливает Times New Roman для run, включая кириллицу."""
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rPr = run._r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.insert(0, rFonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rFonts.set(qn(attr), 'Times New Roman')


def _set_para_format(p, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
                     first_indent_cm=1.25, space_before=0, space_after=6):
    pf = p.paragraph_format
    pf.alignment = align
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    if first_indent_cm:
        pf.first_line_indent = Cm(first_indent_cm)


def add_text(doc, text, bold=False, italic=False,
             align=WD_ALIGN_PARAGRAPH.JUSTIFY,
             first_indent=1.25, size=14,
             space_before=0, space_after=6):
    p = doc.add_paragraph()
    _set_para_format(p, align=align, first_indent_cm=first_indent,
                     space_before=space_before, space_after=space_after)
    run = p.add_run(text)
    _set_run_font(run, size=size, bold=bold, italic=italic)
    return p


